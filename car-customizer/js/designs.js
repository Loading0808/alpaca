// Individual front and rear designs for every car.
//
// Shapes are drawn on the body surface, so they follow each car's own curvature.
// Coordinates on the nose / tail face: z from -1 (left edge) to 1 (right edge),
// y from 0 (bottom of the bumper) to 1 (bonnet / boot-lid edge).
// Shapes on top of the body (headlights that sweep back along the wings, bonnet
// vents): d = metres back from the nose (or forward from the tail), z = fraction
// of the body half-width at that point.
//
// Materials: g grille mesh · k gloss black · l dark lamp lens · w white LED ·
// r red LED · a amber · c chrome · b body colour · p number plate · x carbon

// ---- shapes on the nose / tail face
const R = (m, z0, z1, y0, y1, mir = 0, o) => ({ m, p: [[z0, y0, y1], [z1, y0, y1]], mir, o });          // rectangle
const Q = (m, p, mir = 0, o) => ({ m, p, mir, o });                                                      // free profile: [z, yBottom, yTop] points
const C = (m, z, y, r, mir = 0, o) => ({ m, t: 'c', z, y, r, mir, o });                                  // circle, r in metres
/** Trapezoid centred on zc: half-width wb at the bottom, wt at the top. */
const TZ = (m, zc, wb, wt, y0, y1, o) => Q(m, wt >= wb
  ? [[zc - wt, y1, y1], [zc - wb, y0, y1], [zc + wb, y0, y1], [zc + wt, y1, y1]]
  : [[zc - wb, y0, y0], [zc - wt, y0, y1], [zc + wt, y0, y1], [zc + wb, y0, y0]], 0, o);
/** Hexagon / lozenge: half-width w, corners cut by `cut`. */
const HX = (m, zc, w, cut, y0, y1, o) => { const ym = (y0 + y1) / 2; return Q(m, [[zc - w, ym, ym], [zc - w + cut, y0, y1], [zc + w - cut, y0, y1], [zc + w, ym, ym]], 0, o); };
/** Ellipse. */
const EL = (m, zc, yc, rz, ry, mir = 0, o) => { const p = []; for (let i = 0; i <= 10; i++) { const u = -1 + i / 5, h = ry * Math.sqrt(Math.max(0, 1 - u * u)); p.push([zc + u * rz, yc - h, yc + h]); } return Q(m, p, mir, o); };

// ---- shapes on top of the body (always mirrored left / right)
const TQ = (m, p, o) => ({ m, p, o });                                  // [d, zInner, zOuter] points
const TC = (m, d, z, rd, rz, o) => ({ m, t: 'c', d, z, rd, rz, o });    // ellipse: rd along the car, rz across (metres)

const lamp = {
  /** Swept-back lamp: wide at the nose, tapering along the wing. */
  swept({ d0 = 0.05, d1 = 0.52, zo = 0.9, w0 = 0.4, w1 = 0.1, proj = 2 } = {}) {
    const dm = (d0 + d1) / 2, wm = w0 * 0.62 + w1 * 0.38, out = [
      TQ('l', [[d0, zo - w0, zo], [dm, zo - wm, zo], [d1, zo - w1, zo]]),
      TQ('w', [[d0 + 0.03, zo - w0 + 0.015, zo - w0 + 0.045], [dm, zo - wm + 0.012, zo - wm + 0.038], [d1 - 0.03, zo - w1 + 0.008, zo - w1 + 0.028]], 1),
    ];
    for (let i = 0; i < proj; i++) out.push(TC('w', d0 + 0.13 + i * 0.115, zo - 0.11 - (w0 - 0.3) * 0.2 + i * 0.012, 0.05, 0.045, 1));
    return out;
  },
  /** Narrow blade lamp with an LED signature line. */
  slit({ d0 = 0.06, d1 = 0.48, zo = 0.9, w0 = 0.2, w1 = 0.05 } = {}) {
    return [TQ('l', [[d0, zo - w0, zo], [d1, zo - w1, zo]]), TQ('w', [[d0 + 0.03, zo - w0 + 0.02, zo - w0 + 0.05], [d1 - 0.04, zo - w1 + 0.01, zo - w1 + 0.03]], 1), TC('w', d0 + 0.12, zo - w0 * 0.42, 0.045, 0.035, 1)];
  },
  /** Oval lamp standing proud on the wing. */
  oval({ d = 0.34, z = 0.63, rd = 0.17, rz = 0.14 } = {}) { return [TC('l', d, z, rd, rz), TC('w', d, z, rd * 0.62, rz * 0.62, 1), TC('l', d, z, rd * 0.3, rz * 0.3, 2)]; },
  /** Flush pop-up lamp covers: just the panel gaps. */
  popup({ d0 = 0.36, d1 = 0.62, zi = 0.46, zo = 0.86 } = {}) { return [TQ('s', [[d0, zi, zo], [d0 + 0.008, zi, zo]]), TQ('s', [[d1, zi, zo], [d1 + 0.008, zi, zo]]), TQ('s', [[d0, zi, zi + 0.012], [d1, zi, zi + 0.012]]), TQ('s', [[d0, zo - 0.012, zo], [d1, zo - 0.012, zo]])]; },
};
const rounds = (zs, y, r, m = 'r') => zs.flatMap((z, i) => [C('l', z, y, r + 0.016, 1), C(m, z, y, r, 1, 1)]);
const bars = (z0, n, w, gap, y0, y1, m = 'r') => Array.from({ length: n }, (_, i) => R(m, z0 + i * (w + gap), z0 + i * (w + gap) + w, y0, y1, 1, 1));

